def number(value):
    shown = f"{d(value):,.2f}".rstrip("0").rstrip(".")
    return shown.replace(",", "\u202f").replace(".", ",")


def quantity(value, unit):
    separator = "" if unit == "%" else " "
    return number(value) + (separator + unit if unit else "")


def inputs_text(fields, values):
    return ", ".join(f"{name.lower()} = {number(value)}" for name, value in zip(fields, values))


